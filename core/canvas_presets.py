"""Общий список пресетов размера холста.

Раньше списки были зашиты в двух диалогах отдельно и не совпадали
(в диалоге создания не было 5120×2880, а подписи отличались форматом).
Теперь источник один — и создание нового коллажа, и изменение размера
текущего холста показывают один и тот же набор.

Раньше почти весь список был 16:9, поэтому квадрат, сторис или
печатный формат приходилось вводить руками. Сейчас пресеты
разбиты на три группы: экранные 16:9, соцсети (1:1, 4:5, 9:16)
и печать (A5/A4/A3 и фотоформаты в пикселях под 300 dpi).
"""

# (ширина, высота) в пикселях — экранная лестница 16:9
CANVAS_SIZES = [
    # Меньше прежнего минимума (1080×720) — для превью, сторис и иконок
    (480, 270),
    (640, 360),
    (854, 480),

    (1080, 720),      # было
    (1280, 720),      # промежуточный: 1080×720 ↔ 1920×1080
    (1920, 1080),     # было
    (2048, 1152),     # промежуточный: 1920×1080 ↔ 2560×1440
    (2560, 1440),     # было
    (2880, 1620),     # промежуточный: 2560×1440 ↔ 3200×1800
    (3200, 1800),     # было
    (3520, 1980),     # промежуточный: 3200×1800 ↔ 3840×2160
    (3840, 2160),     # было
    (4480, 2520),     # промежуточный: 3840×2160 ↔ 5120×2880
    (5120, 2880),     # было (только в диалоге изменения размера)
]

# Форматы соцсетей: (ширина, высота, подпись пропорции)
SOCIAL_SIZES = [
    (1080, 1080, "1:1"),
    (2048, 2048, "1:1"),
    (1080, 1350, "4:5"),
    (1080, 1920, "9:16"),
]

# Печать: пиксели = миллиметры × dpi / 25.4 (книжная ориентация)
PRINT_SIZES = [
    (1181, 1772, "10 × 15 см, 300 dpi"),
    (1535, 2126, "13 × 18 см, 300 dpi"),
    (2362, 3543, "20 × 30 см, 300 dpi"),
    (1240, 1754, "A4, 150 dpi"),
    (1748, 2480, "A5, 300 dpi"),
    (2480, 3508, "A4, 300 dpi"),
    (3508, 4961, "A3, 300 dpi"),
]

# Границы ручного ввода размера.
# ВАЖНО: минимум должен быть не больше самой маленькой стороны
# в списке (270), а максимум — не меньше самой большой (4961 у A3),
# иначе QSpinBox молча обрежет значение пресета.
MIN_SIDE = 100
MAX_SIDE = 10000


def preset_label(width: int, height: int, note: str = None) -> str:
    """Подпись пресета в выпадающем списке."""
    label = "{} × {} px".format(width, height)
    if note:
        label = label + " · " + note
    return label


# [(ключ i18n для заголовка, [(подпись, (ширина, высота)), ...])]
PRESET_GROUPS = [
    (
        "preset_group_screen",
        [(preset_label(w, h), (w, h)) for w, h in CANVAS_SIZES],
    ),
    (
        "preset_group_social",
        [(preset_label(w, h, note), (w, h)) for w, h, note in SOCIAL_SIZES],
    ),
    (
        "preset_group_print",
        [(preset_label(w, h, note), (w, h)) for w, h, note in PRINT_SIZES],
    ),
]

# {подпись: (ширина, высота)} — порядок сохраняется
CANVAS_PRESETS = {
    label: size
    for _group_key, _presets in PRESET_GROUPS
    for label, size in _presets
}

# Обратный индекс: по размеру найти подпись пресета.
_SIZE_LABELS = {}
for _group_key, _presets in PRESET_GROUPS:
    for _label, _size in _presets:
        _SIZE_LABELS.setdefault(_size, _label)


def iter_preset_entries():
    """Плоский поток элементов для выпадающего списка.

    ("group", ключ i18n) — заголовок группы;
    ("preset", подпись, (ширина, высота)) — сам пресет.
    """
    for group_key, presets in PRESET_GROUPS:
        yield ("group", group_key)
        for label, size in presets:
            yield ("preset", label, size)


def label_for_size(width, height):
    """Подпись пресета с таким размером или None."""
    return _SIZE_LABELS.get((width, height))


DEFAULT_PRESET = (1920, 1080)
DEFAULT_PRESET_LABEL = preset_label(*DEFAULT_PRESET)

DEFAULT_LARGE_PRESET = (3840, 2160)
DEFAULT_LARGE_PRESET_LABEL = preset_label(*DEFAULT_LARGE_PRESET)

# Размер холста по умолчанию — ЕДИНЫЙ ИСТОЧНИК.
#
# Раньше значение зависело от того, каким путём приложение дошло до
# холста: CanvasScene() создавалась в 3840×2160, project_io.apply()
# подставлял 1920×1080 для файлов без блока "canvas", а диалоги
# предлагали DEFAULT_PRESET. Одинаковые по смыслу действия давали
# разный результат, а «пустой» холст сразу занимал вчетверо больше
# памяти, чем показывали диалоги.
DEFAULT_CANVAS_SIZE = DEFAULT_PRESET
